/* String-literal regressions, consolidated from the former
 * test_addr_string_literal.c, test_local_char_array_brace_strlit.c,
 * test_long_string_literal.c, test_lua_empty_string.c,
 * test_ptr_array_strlit_size.c, test_unclosed_string_warn.c and
 * test_wide_string_alignment.c:
 *
 * - &"literal" is a valid char(*)[N] lvalue address (codegen ND_STR gap).
 * - `{ STRLIT }` for a local char/wide-char array == the bare form
 *   (C11 6.7.9p14), not a scalar-per-element init.
 * - String literals longer than 2048 bytes must decode completely
 *   (the lexer's scratch buffer used to truncate at 2048).
 * - Empty strings intern to one object.
 * - `T *arr[] = { "lit" }` sizes by elements, not strlen.
 * - A missing closing quote in an unused macro warns, not hard-errors.
 * - Wide string literals emit 4/2-byte aligned.
 */
#include <assert.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <wchar.h>

/* ---- address-of string literal (&"abc") (was test_addr_string_literal.c) ---- */

#include <assert.h>
#include <string.h>
#include <stdio.h>

static int test_addr_string_literal(void) {
    /* Exact util-linux isosize.c shape: memcmp against &"literal". */
    char label[8] = "\1CD001\1";
    assert(memcmp(&label, &"\1CD001\1", 8) == 0);
    assert(memcmp(&label, &"\1CD002\1", 8) != 0);

    /* Type correctness: &"abc" is char(*)[4], not char** -- dereferencing
     * it yields the 4-byte array itself (3 chars + NUL), matching real
     * gcc exactly (verified: `sizeof(*&"abc")` == 4 under gcc). */
    assert(sizeof(*&"abc") == 4);
    assert(sizeof(&"abc") == sizeof(void *));
    char (*p)[4] = &"abc";
    assert(strcmp(*p, "abc") == 0);

    /* The address really is the literal's own storage -- taking it twice
     * yields the same location (string literals may be pooled/shared). */
    assert(&"xyz" == &"xyz" || memcmp(&"xyz", &"xyz", 4) == 0);

    printf("OK\n");
    return 0;
}

/* ---- brace-wrapped { STRLIT } local char-array init (was test_local_char_array_brace_strlit.c) ---- */

#include <stdio.h>
#include <string.h>
#include <wchar.h>

static int test_local_char_array_brace_strlit(void)
{
    /* The exact bug shape: a NUL-prefixed string with an unwritten byte
     * at every non-zero index if the array-content copy stops after one
     * corrupted element. */
    const char units[] = {"\0KMGTPEZY"};
    if (sizeof(units) != 10) {
        printf("FAIL: sizeof(units) = %d, expected 10\n", (int)sizeof(units));
        return 1;
    }
    static const char expect[10] = "\0KMGTPEZY";
    if (memcmp(units, expect, 10) != 0) {
        printf("FAIL: units[] content mismatch:");
        for (int i = 0; i < 10; i++) printf(" %d", (unsigned char)units[i]);
        printf("\n");
        return 2;
    }

    /* Non-const local, plain char array. */
    char plain[] = {"hello"};
    if (strcmp(plain, "hello") != 0 || sizeof(plain) != 6) {
        printf("FAIL: plain = \"%s\" sizeof=%d, expected \"hello\"/6\n",
               plain, (int)sizeof(plain));
        return 3;
    }

    /* Trailing comma inside the superfluous brace: `{ STRLIT, }`. */
    const char trailing[] = {"world",};
    if (strcmp(trailing, "world") != 0) {
        printf("FAIL: trailing = \"%s\", expected \"world\"\n", trailing);
        return 4;
    }

    /* Wide string in braces must still decode via the wide-string path,
     * not the byte-oriented one. */
    const wchar_t wide[] = {L"wide"};
    if (wide[0] != L'w' || wide[1] != L'i' || wide[2] != L'd' ||
        wide[3] != L'e' || wide[4] != L'\0' ||
        sizeof(wide) / sizeof(wide[0]) != 5) {
        printf("FAIL: wide[] mismatch, len=%d\n",
               (int)(sizeof(wide) / sizeof(wide[0])));
        return 5;
    }

    /* Regression guard: a genuine one-pointer array of char* initialized
     * BY a string literal (not sized BY one) must still work -- this is
     * the TY_PTR-excluded case local_init_one's existing bare-STR branch
     * (and the array-of-pointers case entirely) must not regress. */
    const char *ptrs[] = {"vec_"};
    if (sizeof(ptrs) / sizeof(ptrs[0]) != 1 || strcmp(ptrs[0], "vec_") != 0) {
        printf("FAIL: ptrs[] mismatch\n");
        return 6;
    }

    printf("ok\n");
    return 0;
}

